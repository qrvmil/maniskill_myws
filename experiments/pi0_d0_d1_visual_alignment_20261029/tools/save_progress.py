"""Publish a bounded, immutable evidence snapshot, verifying every uploaded byte."""
from pathlib import Path
import argparse,datetime,hashlib,json,re,shutil,subprocess,fcntl
from huggingface_hub import HfApi,hf_hub_download,CommitOperationAdd
BASE=Path('/workspace/visual-alignment-repro-20261029')
ROOT=BASE/'maniskill_myws'
REL=Path('experiments/pi0_d0_d1_visual_alignment_20261029')
DEST=ROOT/REL
HF_REPO='qrvmil/pi0-d0-d1-three-adaptations-visual-alignment-20261029'
lockpath=BASE/'run/git_progress.lock';lockpath.parent.mkdir(parents=True,exist_ok=True)
publication_lock=lockpath.open('a');fcntl.flock(publication_lock,fcntl.LOCK_EX)
parser=argparse.ArgumentParser();parser.add_argument('message');args=parser.parse_args()
stamp=datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ')
# Logs and JSON here are generated by the explicit preflight commands, never env dumps.
for p in (BASE/'evidence').iterdir():
 if p.name=='vast-capabilities.json' or p.suffix not in {'.json','.log','.txt','.exitcode','.patch'}:continue
 shutil.copy2(p,DEST/'evidence'/p.name)
# Explicit generated run logs/metrics only; never recurse into assets/checkpoint/cache trees.
for src in (BASE/'run/evidence').glob('*.json'):
 shutil.copy2(src,DEST/'evidence'/src.name)
for stage in ['d0','full','expert']:
 src=BASE/'run/sft'/stage/'metrics.jsonl'
 if src.exists():shutil.copy2(src,DEST/'evidence'/f'{stage}_metrics.jsonl')
src=BASE/'run/rl/updates.jsonl'
if src.exists():shutil.copy2(src,DEST/'evidence/rl_updates.jsonl')
for src in Path('/var/log/portal').glob('pi0_va_*.log'):
 shutil.copy2(src,DEST/'evidence'/src.name)
live={'utc':stamp,'phases':{},'final_episodes':len(list((BASE/'run/final').glob('*/*/*/episode.json')))}
for stage in ['d0','full','expert']:
 metrics=BASE/'run/sft'/stage/'metrics.jsonl';latest=BASE/'run/sft'/stage/'latest.json'
 last=json.loads(metrics.read_text().splitlines()[-1]) if metrics.exists() and metrics.stat().st_size else None
 live['phases'][stage]={'latest_update':None if last is None else last['step'],'durable_local':json.loads(latest.read_text()) if latest.exists() else None}
write_live=DEST/'LIVE_STATUS.json';write_live.write_text(json.dumps(live,indent=2)+'\n')
telemetry=Path('/var/log/portal/pi0_preflight_telemetry.log')
if telemetry.exists():shutil.copy2(telemetry,DEST/'evidence/gpu-telemetry.csv')
for p in [Path('/opt/supervisor-scripts/pi0_preflight_telemetry.sh'),Path('/etc/supervisor/conf.d/pi0_preflight_telemetry.conf'),Path('/opt/supervisor-scripts/pi0_model_preflight.sh'),Path('/etc/supervisor/conf.d/pi0_model_preflight.conf'),Path('/opt/supervisor-scripts/pi0_va_cache_d0.sh'),Path('/etc/supervisor/conf.d/pi0_va_cache_d0.conf')]:
 if p.exists():shutil.copy2(p,DEST/'evidence'/p.name)
allowed={'.json','.jsonl','.log','.txt','.md','.csv','.py','.sh','.conf','.exitcode','.patch'}
files=[p for p in DEST.rglob('*') if p.is_file() and p.suffix in allowed and '__pycache__' not in p.parts]
patterns=[r'gh[pousr]_[A-Za-z0-9]{20,}',r'hf_[A-Za-z0-9]{20,}',r'-----BEGIN (?:RSA |OPENSSH |EC )?PRIVATE KEY-----\n[A-Za-z0-9+/]',r'Bearer\s+[A-Za-z0-9._-]{20,}',r'[?&](?:token|X-Amz-Signature|X-Goog-Signature)=']
changed=subprocess.check_output(['git','diff','HEAD','--name-only','--','scripts/adaptation'],cwd=ROOT,text=True).splitlines()
shared=[ROOT/name for name in changed]
for p in files+shared:
 text=p.read_text()
 if any(re.search(pattern,text) for pattern in patterns):raise ValueError('Potential secret; publication blocked: '+str(p))
subprocess.run(['git','add',str(REL),*[str(p.relative_to(ROOT)) for p in shared]],cwd=ROOT,check=True)
subprocess.run(['git','add','-f',*[str(p.relative_to(ROOT)) for p in files]],cwd=ROOT,check=True)
if subprocess.run(['git','diff','--cached','--quiet'],cwd=ROOT).returncode:
 subprocess.run(['git','commit','-m',args.message],cwd=ROOT,check=True)
subprocess.run(['git','push','origin','HEAD'],cwd=ROOT,check=True)
head=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
branch=subprocess.check_output(['git','branch','--show-current'],cwd=ROOT,text=True).strip()
remote=subprocess.check_output(['git','ls-remote','origin','refs/heads/'+branch],cwd=ROOT,text=True).split()[0]
assert remote==head
snapshot=BASE/'private/publication_snapshots'/stamp;snapshot.mkdir(parents=True)
for p in files:
 out=snapshot/p.relative_to(DEST);out.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,out)
for p in shared:
 out=snapshot/'code'/p.relative_to(ROOT);out.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(p,out)
api=HfApi();all_paths=[p for p in snapshot.rglob('*') if p.is_file()]
state_path=BASE/'private/verified_evidence_state.json'
try:previous=json.loads(state_path.read_text())['hashes'] if state_path.exists() else {}
except (KeyError,json.JSONDecodeError):previous={}
hashes={str(p.relative_to(snapshot)):hashlib.sha256(p.read_bytes()).hexdigest() for p in all_paths}
paths=[p for p in all_paths if previous.get(str(p.relative_to(snapshot)))!=hashes[str(p.relative_to(snapshot))]]
operations=[CommitOperationAdd(path_in_repo='preflight/'+str(p.relative_to(snapshot)),path_or_fileobj=str(p)) for p in paths]
for start in range(0,len(operations),80):
 commit=api.create_commit(HF_REPO,operations=operations[start:start+80],commit_message=args.message)
for p in paths:
 downloaded=hf_hub_download(HF_REPO,'preflight/'+str(p.relative_to(snapshot)),revision=commit.oid)
 assert Path(downloaded).read_bytes()==p.read_bytes()
temporary=state_path.with_suffix('.tmp');temporary.write_text(json.dumps(dict(hashes=hashes,hf_commit=commit.oid),indent=2)+'\n');temporary.replace(state_path)
receipt=dict(utc=stamp,github_commit=head,hf_commit=commit.oid,files=len(paths),full_readback=True,unchanged_previously_verified_files=len(all_paths)-len(paths))
(BASE/'evidence'/('publication-'+stamp+'.json')).write_text(json.dumps(receipt,indent=2)+'\n')
print('EVIDENCE_DURABLE',json.dumps(receipt),flush=True)
